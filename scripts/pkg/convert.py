#!/usr/bin/env python3
"""Splits the phase scripts (scripts/lfs/*-inside.sh) into one autark-pkg recipe per package.

    python3 -I scripts/pkg/convert.py            # from the repo root; rewrites scripts/pkg/*.sh

Each recipe keeps its function body from the phase script, with three changes: T_* and the boot script's
variables become literal names, `/sources/` becomes `$srcdir/` (autark-pkg's folder of the package's sources),
and install commands get DESTDIR when the whole body can stage (see `stage`). Sources and checksums come from
the LFS book's lists (sources/lfs-*), phase-8a-packages.md and sources/extra.tsv. A recipe without the
GENERATED line was taken over by hand and is never overwritten.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LFS = os.path.join(ROOT, 'scripts/lfs')
OUT = os.path.join(ROOT, 'scripts/pkg')
MARK = '# GENERATED by convert.py'

# The phase scripts in build order: a package built again later (systemd, shadow, freetype) takes its last body.
SCRIPTS = [('ch8-inside.sh', 'LFS 13.1-systemd chapter 8'), ('blfs-crypto-inside.sh', 'disk encryption and TPM'),
           ('step6-boot-inside.sh', 'build guide Step 6'), ('phase8a-inside.sh', 'Phase 8a, the Wayland desktop')]
# Steps that configure this machine rather than install a package; they stay in their phase scripts.
NOT_PACKAGES = {'stripping', 'cleanup', 'initramfs', 'sb-key', 'uki', 'services', 'tss-user', 'freetype-pass1'}
# Tracked file lists recorded under another name, and the package they belong to.
RENAME = {'systemd-crypto': 'systemd', 'systemd-pam': 'systemd', 'shadow-pam': 'shadow',
          'freetype-pass2': 'freetype', 'firmware': 'linux-firmware', 'microcode': 'intel-microcode'}
# Bodies run before a package's own (the step that used to precede it).
PREPEND = {'tpm2-tss': 'tss-user'}
# Dependencies the scripts' comments state but no table has (blfs-crypto-inside.sh's diagram, PAM in 8a).
DEPENDS = {'lvm2': ['libaio'], 'json-c': ['cmake'], 'cryptsetup': ['lvm2', 'popt', 'json-c'], 'tpm2-tss': ['json-c'],
           'systemd': ['cryptsetup', 'tpm2-tss', 'pefile', 'pyelftools', 'linux-pam'], 'shadow': ['linux-pam'],
           'openssh': ['linux-pam'], 'dracut': ['cpio', 'systemd']}
# Cycles: harfbuzz is first built on freetype pass 1 (built twice); WirePlumber is PipeWire's session
# manager, needed when it runs, not to build it.
NOT_DEPENDS = {('harfbuzz', 'freetype'), ('pipewire', 'wireplumber')}
VERSION = {'tcl8.6.18-src.tar.gz': '8.6.18', 'expect5.45.4.tar.gz': '5.45.4', 'LVM2.2.03.42.tgz': '2.03.42',
           'sqlite-autoconf-3530400.tar.gz': '3.53.4', 'libliftoff-v0.5.0.tar.gz': '0.5.0',
           'geist-font-v1.8.1.zip': '1.8.1'}
ARCHIVE = re.compile(r'\.(tar\.(xz|gz|bz2|zst)|tgz|tbz2|zip)$')


def die(message):
    sys.exit('convert.py: ' + message)


def read(path):
    with open(path) as f:
        return f.read()


def functions(text):
    """Every top-level `name() {` ... `}` body."""
    out, lines, i = {}, text.split('\n'), 0
    while i < len(lines):
        m = re.match(r'^((?:pkg|step)_\w+)\(\) \{$', lines[i])
        if not m:
            i += 1
            continue
        j = i + 1
        while lines[j] != '}':
            j += 1
        out[m.group(1)] = '\n'.join(lines[i + 1:j])
        i = j + 1
    return out


def run_lines(text, script):
    """(name, tarball or None, function) in build order."""
    variables = dict(re.findall(r'^(T_\w+|FW|UCODE)=(\S+)', text, re.M))
    found = []
    if script == 'ch8-inside.sh':
        for name, tarball, fn in re.findall(r'^\s+\w+\) run_pkg (\S+) (\S+) (\S+) ;;$', text, re.M):
            found.append((name, tarball, fn))
    else:
        for name, tarball, fn in re.findall(r'^run_pkg\s+(\S+)\s+(\S+)\s+(\S+)\s*$', text, re.M):
            tarball = re.sub(r'"?\$(\w+)"?', lambda m: variables[m.group(1)], tarball)
            found.append((name, tarball, fn))
    return [(n, None if t == '-' else t, fn) for n, t, fn in found], variables


def lfs_sources():
    """Tarball → (url, checksum) from the book's wget-list and md5sums."""
    urls = [l.strip() for l in open(os.path.join(OUT, 'sources/lfs-13.1-wget-list')) if l.strip()]
    md5 = dict(reversed(l.split()) for l in open(os.path.join(OUT, 'sources/lfs-13.1-md5sums')) if l.strip())
    return {u.rsplit('/', 1)[1]: (u, 'md5:' + md5[u.rsplit('/', 1)[1]]) for u in urls}


def spec_sources():
    """Tarball → (url, checksum, needed-by text, package title) from phase-8a-packages.md."""
    out = {}
    for line in read(os.path.join(ROOT, 'docs/specs/phase-8a-packages.md')).split('\n'):
        cells = [c.strip() for c in re.split(r'(?<!\\)\|', line)]
        if len(cells) < 9 or not cells[5].startswith('http'):
            continue
        url, sums, needed, title = cells[5], cells[6], cells[7], re.sub(r'[*(].*', '', cells[2]).strip()
        # Only the names themselves: asides in brackets or backticks mention packages that aren't dependents.
        needed = re.sub(r'\([^)]*\)|`[^`]*`', '', needed)
        m = re.search(r'sha256 ([0-9a-f]{64})', sums) or re.search(r'md5 ([0-9a-f]{32})', sums)
        kind = 'sha256' if m and len(m.group(1)) == 64 else 'md5'
        out[url.rsplit('/', 1)[1]] = (url, f'{kind}:{m.group(1)}' if m else '-', needed, title)
    return out


def extra_sources():
    out = {}
    for line in open(os.path.join(OUT, 'sources/extra.tsv')):
        if line.strip() and not line.startswith('#'):
            name, url, checksum = line.rstrip('\n').split('\t')[:3]
            out[name] = (url, checksum)
    return out


def version_of(tarball, name):
    if tarball in VERSION:
        return VERSION[tarball]
    stem = ARCHIVE.sub('', tarball)
    m = re.search(r'[-_]v?(\d[\w.+-]*?)(\.src|-src)?$', stem)
    if not m:
        die(f'no version in {tarball} ({name})')
    return m.group(1)


INSTALL = [
    (re.compile(r'^(\s*)make\b(?=.*\binstall)'), r'\1make DESTDIR="$DESTDIR"'),
    (re.compile(r'^(\s*)(ninja|meson install|cmake --install)\b(?=.*\binstall)'), r'\1DESTDIR="$DESTDIR" \2'),
    (re.compile(r'^(\s*)pip3 install\b'), r'\1pip3 install --root="$DESTDIR" --ignore-installed'),
]
# Writes outside the staging folder, or needs root: such a body is tracked instead (built and installed as root,
# its new and changed files recorded afterwards).
ABSOLUTE = re.compile(r'(?<![=\w./${}-])/(usr|etc|var|lib|lib64|bin|sbin|opt|boot|srv|run|home)(/|\b)')
ROOT_ONLY = re.compile(r'\b(chown|chgrp|useradd|groupadd|usermod|userdel|su|systemctl|setcap|mknod|make-ca|'
                       r'ldconfig|pwconv|grpconv|systemd-machine-id-setup|chpasswd)\b')


def stage(body):
    """The body with DESTDIR on its installs, or None if it can't stage."""
    out = []
    for line in body.split('\n'):
        if line.lstrip().startswith('#'):
            out.append(line)
            continue
        for pattern, replacement in INSTALL:
            line = pattern.sub(replacement, line)
        code = re.sub(r"'[^']*'", "''", line) if 'sed' not in line else line
        if ABSOLUTE.search(code) or ROOT_ONLY.search(code):
            return None
        out.append(line)
    staged = '\n'.join(out)
    return staged if '$DESTDIR' in staged else None


def main():
    lfs, spec, extra = lfs_sources(), spec_sources(), extra_sources()
    known = {**{k: v[:2] for k, v in spec.items()}, **lfs, **extra}
    packages, order, imports = {}, [], {}
    for script, origin in SCRIPTS:
        text = read(os.path.join(LFS, script))
        bodies = functions(text)
        runs, variables = run_lines(text, script)
        for listed, tarball, fn in runs:
            if fn not in bodies:
                die(f'{script}: {fn} has no body')
            if listed in NOT_PACKAGES and listed not in PREPEND.values():
                continue
            name = RENAME.get(listed, listed).lower()
            if listed in PREPEND.values():
                continue
            body = bodies[fn]
            for target, step in PREPEND.items():
                if name == target:
                    step_fn = next(f for n, _, f in runs if n == step)
                    body = bodies[step_fn] + '\n' + body
            for var, value in variables.items():
                body = re.sub(r'\$\{?' + var + r'\b\}?', value, body)
            body = body.replace('/sources/', '$srcdir/')
            imports.setdefault(name, [])
            if listed not in imports[name]:
                imports[name].append(listed)
            if name not in packages:
                order.append(name)
            packages[name] = dict(name=name, tarball=tarball, body=body, script=script, origin=origin, fn=fn)

    # A dependency named in the spec's "Needed by" column: package X needed by Y means Y depends on X.
    titles = {}
    for tarball, (_, _, needed, title) in spec.items():
        owner = next((p for p in packages.values() if p['tarball'] == tarball), None)
        if owner:
            titles[owner['name']] = title
            for other in packages:
                if other != owner['name'] and re.search(r'(?<![\w-])' + re.escape(other) + r'(?![\w-])', needed, re.I):
                    if (other, owner['name']) not in NOT_DEPENDS:
                        packages[other].setdefault('depends', []).append(owner['name'])

    written, staged_count, missing, unknown, recipes = [], 0, [], [], []
    for name in order:
        p = packages[name]
        sources = [p['tarball']] if p['tarball'] else []
        # Anything else the body unpacks or patches with: a known file name mentioned in it.
        for file in sorted(known, key=len, reverse=True):
            if file not in sources and re.search(r'(?<![\w.-])' + re.escape(file) + r'(?![\w.-])', p['body']):
                sources.append(file)
        # And files the body reads from the sources folder by name.
        for file in re.findall(r'\$srcdir/([\w.+-]+)', p['body']):
            if file not in sources:
                sources.append(file)
        if not sources:
            die(f'{name}: no sources')
        entries = []
        for file in sources:
            if file not in known:
                unknown.append(f'{name}: {file}')
                continue
            url, checksum = known[file]
            entries.append((file if url.rsplit('/', 1)[1] == file else f'{file}::{url}', url, checksum))
            if checksum == '-':
                missing.append(f'{name}: {file}')
        version = version_of(p['tarball'] or sources[0], name)
        staged = stage(p['body'])
        staged_count += staged is not None
        depends = sorted(set(p.get('depends', []) + DEPENDS.get(name, [])))
        recipes.append((name, p, version, entries, staged, depends))
    if unknown:
        die('no URL for these; add them to sources/extra.tsv:\n  ' + '\n  '.join(unknown))
    for name, p, version, entries, staged, depends in recipes:
        path = os.path.join(OUT, name + '.sh')
        if os.path.exists(path) and MARK not in read(path):
            print(f'kept {name}.sh (taken over by hand)')
            continue
        lines = [f'# {name} {version}: from {p["origin"]} (scripts/lfs/{p["script"]}, {p["fn"]}).',
                 f'{MARK}; delete this line to take the recipe over by hand.',
                 f'name={name}', f'version={version}', 'release=1']
        if name in titles:
            lines.append(f'description="{titles[name]}"')
        lines.append('source=(' + ' '.join(e[0] if '::' in e[0] else e[1] for e in entries) + ')')
        lines.append('checksums=(' + ' '.join(e[2] for e in entries) + ')')
        if depends:
            lines.append('depends=(' + ' '.join(depends) + ')')
        others = [i for i in imports[name] if i != name]
        if others:
            lines.append('imports=(' + ' '.join(others) + ')')
        lines.append('mode=' + ('staged' if staged else 'tracked'))
        lines += ['', 'build() {', staged or p['body'], '}', '']
        with open(path, 'w') as f:
            f.write('\n'.join(lines))
        written.append(name)
    with open(os.path.join(OUT, 'order'), 'w') as f:
        f.write('# Build order of the converted recipes (the phase scripts\' order). Generated by convert.py.\n')
        f.write('\n'.join(order) + '\n')
    print(f'{len(written)} recipes, {staged_count} staged, {len(order) - staged_count} tracked')
    for m in missing:
        print('no checksum:', m)


if __name__ == '__main__':
    main()
